def build_model(
    channels: Tuple[int, ...] = DEFAULT_CHANNELS,
    gru_hidden: int = DEFAULT_GRU_HIDDEN,
    gru_layers: int = DEFAULT_GRU_LAYERS,
    n_fft: int = DEFAULT_N_FFT,
    hop_length: int = DEFAULT_HOP_LENGTH,
    win_length: int = DEFAULT_WIN_LENGTH,
    sample_rate: int = DEFAULT_SAMPLE_RATE,
    segment_samples: int = DEFAULT_SEGMENT_SAMPLES,
    device: torch.device = torch.device("cpu"),
) -> TinyDCCRN:
    """Construct a TinyDCCRN with the correct STFT-derived input_shape.

    This mirrors build_model() in train_dccrn_3.py.  The STFT probe step
    determines (F, T) from the n_fft and segment_samples so the GRU
    input_size is computed identically to training.
    """
    # Compute STFT output shape using a zero waveform (no audio needed).
    window = torch.hann_window(win_length)
    probe = torch.zeros(1, segment_samples)
    spec = torch.stft(
        probe, n_fft, hop_length, win_length, window,
        return_complex=True, center=True,
    )
    input_shape = (spec.shape[-2], spec.shape[-1])   # (F, T)
    model = TinyDCCRN(channels, gru_hidden, gru_layers, input_shape).to(device)
    return model


def load_checkpoint(
    checkpoint_path: str,
    device: torch.device = torch.device("cpu"),
    strict: bool = True,
) -> Tuple[TinyDCCRN, dict]:
    """Load an Experiment 3 checkpoint produced by train_dccrn_3.py.

    The checkpoint dict contains:
        model_state_dict        : OrderedDict — weights
        model_config            : {channels, gru_hidden_size, gru_layers}
        stft_config             : {sample_rate, n_fft, hop_length, win_length}
        epoch                   : int
        validation_loss         : float
        best_validation_loss    : float
        config                  : full training Config as dict
        optimizer_state_dict    : (ignored at inference)
        scheduler_state_dict    : (ignored at inference)

    Args:
        checkpoint_path : path to .pth file
        device          : target device
        strict          : if True, raise on missing/unexpected keys

    Returns:
        model     : TinyDCCRN with weights loaded, in eval() mode
        meta      : the full checkpoint dict (epoch, loss, configs, …)
    """
    ckpt = torch.load(checkpoint_path, map_location=device, weights_only=False)

    mc = ckpt.get("model_config", {})
    sc = ckpt.get("stft_config", {})

    channels    = tuple(mc.get("channels", DEFAULT_CHANNELS))
    gru_hidden  = int(mc.get("gru_hidden_size", DEFAULT_GRU_HIDDEN))
    gru_layers  = int(mc.get("gru_layers", DEFAULT_GRU_LAYERS))
    n_fft       = int(sc.get("n_fft", DEFAULT_N_FFT))
    hop_length  = int(sc.get("hop_length", DEFAULT_HOP_LENGTH))
    win_length  = int(sc.get("win_length", DEFAULT_WIN_LENGTH))
    sample_rate = int(sc.get("sample_rate", DEFAULT_SAMPLE_RATE))

    # segment_samples is derived from the full config if available
    full_cfg    = ckpt.get("config", {})
    seg_sec     = float(full_cfg.get("segment_seconds", 2.0))
    segment_samples = int(sample_rate * seg_sec)

    model = build_model(
        channels=channels,
        gru_hidden=gru_hidden,
        gru_layers=gru_layers,
        n_fft=n_fft,
        hop_length=hop_length,
        win_length=win_length,
        sample_rate=sample_rate,
        segment_samples=segment_samples,
        device=device,
    )

    missing, unexpected = model.load_state_dict(ckpt["model_state_dict"], strict=strict)
    model.eval()

    return model, ckpt


def load_quantized_model(
    quantized_checkpoint_path: str,
    base_checkpoint_path: str = "C:/SIH/Experiment_03_Identity_Residual/checkpoints/Experiment_03_best.pth",
    device: torch.device = torch.device("cpu"),
) -> Tuple[nn.Module, dict]:
    """Load a dynamic INT8 quantized TinyDCCRN model checkpoint.

    Reconstructs the model architecture, applies dynamic quantization structure,
    and loads the quantized state_dict.
    """
    try:
        import torch.ao.quantization as quantization
    except ImportError:
        import torch.quantization as quantization

    base_model, meta = load_checkpoint(base_checkpoint_path, device=device)
    base_model.eval()

    q_model = quantization.quantize_dynamic(
        base_model,
        qconfig_spec={nn.GRU, nn.Linear},
        dtype=torch.qint8
    )

    ckpt = torch.load(quantized_checkpoint_path, map_location=device, weights_only=False)
    state = ckpt.get("model_state_dict", ckpt)
    q_model.load_state_dict(state)
    q_model.eval()

    return q_model, meta

